ROLE_PERMISSIONS = {
    "ROLE_ADMIN": {"INCIDENT_READ","INCIDENT_CREATE","INCIDENT_UPDATE","DISPATCH_CREATE","TEAM_MANAGE","OFFICIAL_MANAGE"},
    "ROLE_DISPATCHER": {"INCIDENT_READ","INCIDENT_CREATE","INCIDENT_UPDATE","DISPATCH_CREATE","TEAM_MANAGE"},
    "ROLE_FIELD_RESCUE": {"INCIDENT_READ","INCIDENT_CREATE"},
}

def has_permission(role: str, permission: str) -> bool:
    return permission in ROLE_PERMISSIONS.get(role, set())
